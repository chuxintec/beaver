def make(destination):
    destination=Path(destination)
    if destination.exists():raise SystemExit('Font output exists')
    glyphs={}; cmap={}; metrics={}
    for ch in ['.notdef']+[chr(x) for x in range(32,127)]:
        name='notdef' if ch=='.notdef' else 'u%04X'%ord(ch)
        pattern=PATTERNS.get(ch.upper(),PATTERNS['-'])
        pen=TTGlyphPen(None)
        for y,row in enumerate(pattern):
            for x,cell in enumerate(row):
                if cell=='1':
                    left=50+x*100;bottom=100+(6-y)*100
                    pen.moveTo((left,bottom));pen.lineTo((left,bottom+86));pen.lineTo((left+86,bottom+86));pen.lineTo((left+86,bottom));pen.closePath()
        glyphs[name]=pen.glyph();metrics[name]=(600,50)
        if ch!='.notdef':cmap[ord(ch)]=name
    font=FontBuilder(1000,isTTF=True);font.setupGlyphOrder(list(glyphs));font.setupCharacterMap(cmap)
    font.setupGlyf(glyphs);font.setupHorizontalMetrics(metrics);font.setupHorizontalHeader(ascent=900,descent=-100)
    font.setupNameTable({'familyName':'Beaver Sample','styleName':'Regular','uniqueFontIdentifier':'BeaverSample-Regular-1','fullName':'Beaver Sample Regular','psName':'BeaverSample-Regular','version':'Version 1.0'})
    font.setupOS2(sTypoAscender=900,sTypoDescender=-100,usWinAscent=900,usWinDescent=100)
    font.setupPost();font.setupMaxp();destination.parent.mkdir(parents=True,exist_ok=True);font.save(destination)

if __name__=='__main__':make(sys.argv[1])
